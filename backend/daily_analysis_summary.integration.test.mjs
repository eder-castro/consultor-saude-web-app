async function run(command, args, input) {
  const child = Bun.spawn([command, ...args], {
    stdin: input === undefined ? "ignore" : new Blob([input]),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [code, stdout, stderr] = await Promise.all([
    child.exited,
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
  ]);
  if (code !== 0) throw new Error(`${command}: ${stderr || stdout}`);
  return stdout;
}

async function sql(input) {
  return run(join(bin, "psql"), [
    "--no-psqlrc", "-X", "-v", "ON_ERROR_STOP=1", "-qAt",
    "-h", socket, "-p", "15440", "-U", "postgres", "-d", "postgres",
  ], input);
}

async function dailyContext(ownerId) {
  const result = await sql(
    `select public.health_daily_analysis_context('${ownerId}')::text;`,
  );
  return JSON.parse(result.trim());
}

