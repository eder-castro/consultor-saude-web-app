integrationTest("snapshots seven complete days, reconciles facts, isolates owners and remains unchanged", async () => {
  const first = await dailyContext(owner);
  expect(first.ok).toBe(true);
  expect(first.origem).toBe("primeiro_uso");
  expect(first.gerado_em).toMatch(/Z$/);
  expect(first.para_dia).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  expect(first.periodo).toEqual({
    inicio: await sql(
      `select ((clock_timestamp() at time zone 'America/Sao_Paulo')::date - 7)::text;`,
    ).then((value) => value.trim()),
    fim: await sql(
      `select ((clock_timestamp() at time zone 'America/Sao_Paulo')::date - 1)::text;`,
    ).then((value) => value.trim()),
  });

  const days = first.resumo.dias;
  expect(days).toHaveLength(7);
  expect(days.map(({ data }) => data)).toEqual([
    -7, -6, -5, -4, -3, -2, -1,
  ].map((offset) => {
    const [year, month, day] = first.para_dia.split("-").map(Number);
    const date = new Date(Date.UTC(year, month - 1, day + offset));
    return date.toISOString().slice(0, 10);
  }));

  const byOffset = (offset) => {
    const [year, month, day] = first.para_dia.split("-").map(Number);
    const date = new Date(Date.UTC(year, month - 1, day + offset));
    const data = date.toISOString().slice(0, 10);
    return days.find((entry) => entry.data === data);
  };

  expect(byOffset(-2)).toMatchObject({
    refeicoes: 2,
    alimentos_omitidos: 3,
    exercicio_min: 105.27,
    sono_min: 450,
    peso_kg: 70.4,
  });
  expect(byOffset(-2).atividades).toContainEqual({ tipo: "Caminhada", ocorrencias: 1 });
  expect(byOffset(-2).atividades).toContainEqual({ tipo: "Musculação", ocorrencias: 1 });
  expect(byOffset(-2).atividades).toContainEqual({ tipo: "Pedalada", ocorrencias: 1 });
  expect(byOffset(-2).atividades_omitidas).toBe(0);
  expect(byOffset(-2).alimentos).toHaveLength(12);
  expect(byOffset(-2).alimentos).toContainEqual({ item: "Arroz", ocorrencias: 2 });
  expect(byOffset(-2).avisos).toEqual([]);
  expect(byOffset(-1).agua_ml).toBe(2250);
  expect(byOffset(-1).refeicoes).toBe(0);
  expect(byOffset(-3).agua_ml).toBeNull();
  expect(byOffset(-3).exercicio_min).toBeNull();
  expect(byOffset(-3).sono_min).toBe(360);
  expect(byOffset(-6).sono_min).toBe(330);
  expect(byOffset(-4).exercicio_min).toBeNull();
  expect(byOffset(-4).sono_min).toBeNull();
  expect(byOffset(-4).avisos).toContain(
    "1 duração(ões) de exercício não puderam ser interpretadas; o total foi omitido.",
  );
  expect(byOffset(-4).avisos).toContain(
    "1 sessão(ões) de sono com totais contraditórios foram omitidas.",
  );
  expect(days.every((entry) => entry.refeicoes >= 0 && entry.alimentos_omitidos >= 0)).toBe(true);

  const serialized = JSON.stringify(first);
  expect(serialized).not.toContain(owner);
  expect(serialized).not.toContain(otherOwner);
  expect(serialized).not.toContain("Segredo de outra conta");
  expect(serialized).not.toContain("Enviado hoje");
  expect(serialized).not.toContain("import_key");
  expect(serialized).not.toContain("email");
  expect(serialized).not.toContain("midia");

  await sql(`
    insert into public.alimentacao
      (owner_id, data, horario, item, quantidade, evento_tipo, created_at)
    values ('${owner}', current_date - 2, '10:00', 'Alterado após o fechamento',
      '1 porção', 'alimentacao', clock_timestamp() - interval '2 days');
  `);
  expect(await dailyContext(owner)).toEqual(first);
  expect((await sql(
    `select count(*) from public.health_daily_analysis_summaries where owner_id = '${owner}';`,
  )).trim()).toBe("1");
});

integrationTest("parses legacy duration formats and rejects ambiguous weights and units", async () => {
  const parsed = await sql(`
    select jsonb_build_array(
      public.health_daily_parse_duration_minutes('25'),
      public.health_daily_parse_duration_minutes('7h30'),
      public.health_daily_parse_duration_minutes('7h 30'),
      public.health_daily_parse_duration_minutes('7h 30 min'),
      public.health_daily_parse_duration_minutes('45cats'),
      public.health_daily_parse_duration_minutes('7h 90'),
      public.health_daily_parse_weight_kg('94.2 kg'),
      public.health_daily_parse_weight_kg('94 e 96'),
      public.health_daily_parse_weight_kg('94 kg and 96')
    )::text;
  `);
  expect(JSON.parse(parsed.trim())).toEqual([
    25, 450, 450, 450, null, null, 94.2, null, null,
  ]);
});

integrationTest("concurrent first-use calls persist one identical snapshot and other owners cannot see it", async () => {
  const [first, second] = await Promise.all([
    dailyContext(concurrentOwner),
    dailyContext(concurrentOwner),
  ]);
  expect(first).toEqual(second);
  expect(first.origem).toBe("primeiro_uso");
  expect(first.resumo.dias).toHaveLength(7);
  const rows = await sql(
    `select count(*) from public.health_daily_analysis_summaries where owner_id = '${concurrentOwner}';`,
  );
  expect(rows.trim()).toBe("1");
  expect(JSON.stringify(first)).not.toContain("9999");

  const grants = await sql(`
    select has_function_privilege('anon',
      'public.health_daily_analysis_context(uuid)', 'execute')::text
      || ',' ||
      has_function_privilege('anon',
        'public.health_build_daily_analysis_summary(uuid,date,text)', 'execute')::text
      || ',' ||
      has_table_privilege('anon', 'public.health_daily_analysis_summaries', 'SELECT')::text
      || ',' ||
      has_table_privilege('anon', 'public.health_daily_analysis_summaries', 'INSERT')::text
      || ',' ||
      has_table_privilege('anon', 'public.health_daily_analysis_summaries', 'UPDATE')::text
      || ',' ||
      has_table_privilege('anon', 'public.health_daily_analysis_summaries', 'DELETE')::text;
  `);
  expect(grants.trim()).toBe("true,false,true,false,false,false");
});