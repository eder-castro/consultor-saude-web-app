integrationTest("sleep uploads are owner/date scoped, replacing legacy duplicates atomically and retrying without deleting again", async () => {
  const other = "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa";
  await sql(`insert into public.health_users values ('${other}') on conflict do nothing;
    insert into public.sono(owner_id,data,duracao_minutos) values
      ('${owner}','2026-10-08','100 min'),('${owner}','2026-10-08','200 min'),
      ('${other}','2026-10-08','400 min');`);
  const entries = [{ table: "sono", record: { owner_id: owner,
    import_key: "app:77777777-7777-4777-8777-777777777777",
    data: "2026-10-08", duracao_minutos: "345 min",
    sono_profundo_min: "117 min", sono_leve_min: "167 min", sono_rem_min: "61 min", acordado_min: "5 min",
  } }];
  const call = (operation, approvals, rows = entries) => `select public.save_health_records_checked(
    '${owner}','${operation}','${JSON.stringify(rows)}'::jsonb,'${JSON.stringify(approvals)}'::jsonb);`;
  await expect(sql(call("sleep-unapproved", []))).rejects.toThrow("SLEEP_DUPLICATE");
  // The older three-argument RPC must enforce the same guard.
  await expect(sql(`select public.save_health_records('${owner}','sleep-old-client','${JSON.stringify(entries)}');`))
    .rejects.toThrow("SLEEP_DUPLICATE");
  const status = JSON.parse((await sql(`select public.sleep_day_status('${owner}','2026-10-08');`)).trim());
  expect(status.count).toBe(2);
  const approval = [{ data: "2026-10-08", expected_token: status.token }];
  const invalid = [{ table: "hidratacao", record: { owner_id: owner, data: "2026-10-08",
    import_key: "app:88888888-8888-4888-8888-888888888888", quantidade: "invalid" } }];
  await expect(sql(call("sleep-invalid-mixed", approval, [...entries, ...invalid]))).rejects.toThrow();
  expect((await sql(`select count(*) from public.sono where owner_id='${owner}' and data='2026-10-08';`)).trim()).toBe("2");
  const first = JSON.parse((await sql(call("sleep-approved", approval))).trim());
  expect(first.record_refs).toHaveLength(1);
  expect((await sql(`select count(*) from public.sono where owner_id='${owner}' and data='2026-10-08';`)).trim()).toBe("1");
  expect((await sql(`select duracao_minutos from public.sono where owner_id='${other}' and data='2026-10-08';`)).trim()).toBe("400 min");
  // A late retry must return the original outcome, preserving a subsequent edit.
  await sql(`update public.sono set duracao_minutos='350 min' where owner_id='${owner}' and data='2026-10-08';`);
  expect(JSON.parse((await sql(call("sleep-approved", approval))).trim())).toEqual(first);
  expect((await sql(`select duracao_minutos from public.sono where owner_id='${owner}' and data='2026-10-08';`)).trim()).toBe("350 min");
  await expect(sql(call("sleep-stale-approval", approval))).rejects.toThrow("SLEEP_CHANGED");
});