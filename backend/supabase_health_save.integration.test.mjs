integrationTest("date corrections move selected owned rows atomically and replay safely after a lost response", async () => {
  await sql(`
    insert into public.alimentacao(id,owner_id,data,horario,item,quantidade,evento_tipo)
      values (901,'${owner}','2026-09-28','00:15','Arroz','3 colheres','alimentacao');
    insert into public.sono(id,owner_id,data,duracao_minutos,sono_leve_min)
      values (902,'${owner}','2026-09-28','345 min','167 min');
    insert into public.health_users(id) values ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa')
      on conflict do nothing;
    insert into public.peso(id,owner_id,data,valor_kg)
      values (906,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa','2026-09-28','70');
  `);
  const refs = [{ table: "alimentacao", id: "901" }, { table: "sono", id: "902" }];
  const call = (operation, records = refs) => `select public.change_health_record_dates(
    '${owner}','${operation}','2026-09-28','2026-09-27','${JSON.stringify(records)}'::jsonb);`;
  // A missing/foreign row causes all selected rows to remain on their source day.
  await expect(sql(call("11111111-aaaa-4111-8111-111111111111", [...refs, { table: "peso", id: "906" }]))).rejects.toThrow();
  expect(await sql("select data from public.alimentacao where id=901;")).toContain("2026-09-28");
  expect(await sql("select data from public.peso where id=906;")).toContain("2026-09-28");
  const operation = "22222222-aaaa-4222-8222-222222222222";
  expect(JSON.parse((await sql(call(operation))).trim())).toEqual({ ok: true, updated: 2 });
  expect(JSON.parse((await sql(call(operation))).trim())).toEqual({ ok: true, updated: 2 });
  expect(await sql("select data||'/'||horario||'/'||item||'/'||quantidade from public.alimentacao where id=901;"))
    .toContain("2026-09-27/00:15/Arroz/3 colheres");
  expect(await sql("select data||'/'||duracao_minutos||'/'||sono_leve_min from public.sono where id=902;"))
    .toContain("2026-09-27/345 min/167 min");
  await expect(sql(call(operation, [refs[0]]))).rejects.toThrow();
  // Another operation with a stale source date cannot move the row again.
  await expect(sql(call("33333333-aaaa-4333-8333-333333333333"))).rejects.toThrow();
});

