integrationTest("serializes identical corrections and returns one idempotent record", async () => {
  const selectedIds = ["9007199254740993", "9007199254740994", "9007199254740995"];
  await seedSleepRows([
    { id: selectedIds[0], stage: "deep", value: "60 min" },
    { id: selectedIds[1], stage: "light", value: "240 min" },
    { id: selectedIds[2], stage: "rem", value: "120 min" },
  ]);
  await psql("alter table public.sono alter column id restart with 9007199254741000;");

  const results = await Promise.all([
    callConsolidation(selectedIds, 420),
    callConsolidation([...selectedIds].reverse(), 420),
  ]);

  expect(results.map(({ corrected }) => corrected).sort()).toEqual([false, true]);
  expect(results.map(({ replaced }) => replaced).sort()).toEqual([0, 3]);
  expect(new Set(results.map(({ record_id }) => record_id))).toEqual(new Set(["9007199254741000"]));
  expect(await psql("select count(*) from public.sono;")).toBe("1\n");
});

integrationTest(
  "serializes partially overlapping corrections without a partial insert",
  async () => {
    const firstIds = ["9007199254740993", "9007199254740994"];
    const secondIds = ["9007199254740994", "9007199254740995"];
    await seedSleepRows([
      { id: firstIds[0], stage: "deep", value: "60 min" },
      { id: firstIds[1], stage: "light", value: "240 min" },
      {
        id: secondIds[1],
        stage: "deep",
        value: "60 min",
        duration: "420 min",
      },
    ]);
    await psql(`
      update public.sono
         set sono_leve_min = '240 min',
             sono_rem_min = '120 min'
       where id = ${secondIds[1]};
    `);

    const first = callConsolidation(firstIds, 300, 750);
    await Bun.sleep(100);
    const secondStartedAt = performance.now();
    const second = expectRejectedConsolidation(secondIds, 420);
    const [firstResult, secondError] = await Promise.all([first, second]);
    const secondElapsedMs = performance.now() - secondStartedAt;

    expect(firstResult).toMatchObject({ corrected: true, replaced: 2 });
    expect(secondElapsedMs).toBeGreaterThan(400);
    expect(secondError.message).toContain(
      "Um ou mais registros não existem ou não pertencem à conta.",
    );
    expect(await psql("select count(*) from public.sono;")).toBe("2\n");
    expect(
      await psql("select count(*) from public.sono where sleep_correction_key is not null;"),
    ).toBe("1\n");
  },
);

integrationTest("keeps bigint sleep ids exact from selection through the response", async () => {
  const selectedIds = ["9007199254740993", "9007199254740994"];
  await seedSleepRows([
    { id: selectedIds[0], stage: "deep", value: "60 min" },
    { id: selectedIds[1], stage: "light", value: "240 min" },
  ]);
  await psql("alter table public.sono alter column id restart with 9007199254740999;");

  const result = await callConsolidation(selectedIds, 300);

  expect(result.record_id).toBe("9007199254740999");
  expect(typeof result.record_id).toBe("string");
  expect(await psql("select id::text from public.sono;")).toBe("9007199254740999\n");
});
