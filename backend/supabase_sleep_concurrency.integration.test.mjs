const RUN_INTEGRATION_TESTS = process.env.RUN_POSTGRES_INTEGRATION_TESTS === "1";
const integrationTest = RUN_INTEGRATION_TESTS ? test : test.skip;
const OWNER_ID = "8e165e4f-59bc-4b94-9508-4f596ee87584";
const BIGINT_START = "9007199254740993";

let postgresBinDirectory;
let testDirectory;
let dataDirectory;
let socketDirectory;

async function run(command, args, { input } = {}) {
  const process = Bun.spawn([command, ...args], {
    stdin: input === undefined ? "ignore" : new Blob([input]),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [exitCode, stdout, stderr] = await Promise.all([
    process.exited,
    new Response(process.stdout).text(),
    new Response(process.stderr).text(),
  ]);
  if (exitCode !== 0) {
    throw new Error(`${command} ${args.join(" ")} exited with ${exitCode}\n${stderr || stdout}`);
  }
  return stdout;
}

function postgresBinary(name) {
  return join(postgresBinDirectory, name);
}

async function psql(sql) {
  return run(
    postgresBinary("psql"),
    [
      "--no-psqlrc",
      "--set",
      "ON_ERROR_STOP=1",
      "--quiet",
      "--tuples-only",
      "--no-align",
      "--host",
      socketDirectory,
      "--username",
      "postgres",
      "--dbname",
      "postgres",
    ],
    { input: sql },
  );
}

async function callConsolidation(recordIds, totalSleepMinutes, holdTransactionMs = 0) {
  const ids = recordIds.map((id) => `'${id}'`).join(",");
  const holdSql = holdTransactionMs > 0 ? `select pg_sleep(${holdTransactionMs / 1000});` : "";
  const output = await psql(`
    begin;
    select public.consolidate_sleep_records(
      '${OWNER_ID}',
      array[${ids}]::text[],
      ${totalSleepMinutes}
    )::text;
    ${holdSql}
    commit;
  `);
  const jsonLine = output
    .split("\n")
    .map((line) => line.trim())
    .find((line) => line.startsWith("{"));
  if (!jsonLine) throw new Error(`PostgreSQL did not return JSON: ${output}`);
  return JSON.parse(jsonLine);
}

async function expectRejectedConsolidation(recordIds, totalSleepMinutes) {
  try {
    await callConsolidation(recordIds, totalSleepMinutes);
  } catch (error) {
    return error;
  }
  throw new Error("Expected sleep consolidation to be rejected");
}

async function seedSleepRows(rows) {
  const nextGeneratedId = (
    rows.reduce((highest, { id }) => {
      const numericId = BigInt(id);
      return numericId > highest ? numericId : highest;
    }, 0n) + 1n
  ).toString();
  const values = rows
    .map(
      ({ id, stage, value = "60 min", duration = value }) => `(
        ${id},
        '${OWNER_ID}',
        'integration:${id}',
        '2026-08-20',
        '23:00',
        '07:00',
        '${duration}',
        ${stage === "deep" ? `'${value}'` : "null"},
        ${stage === "light" ? `'${value}'` : "null"},
        ${stage === "rem" ? `'${value}'` : "null"},
        ${stage === "awake" ? `'${value}'` : "null"},
        'integration-test'
      )`,
    )
    .join(",\n");
  await psql(`
    insert into public.sono (
      id,
      owner_id,
      import_key,
      data,
      inicio,
      fim,
      duracao_minutos,
      sono_profundo_min,
      sono_leve_min,
      sono_rem_min,
      acordado_min,
      source_file_id
    ) values ${values};
    alter table public.sono alter column id restart with ${nextGeneratedId};
  `);
}

