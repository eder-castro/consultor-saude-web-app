integrationTest("simultaneous daily totals keep one row, preserve drinks, and feed daily and weekly readings", async () => {
  await psql(`
    insert into public.hidratacao
      (owner_id, import_key, data, horario, item, quantidade, source_file_id)
    values
      ('${OWNER_ID}', 'app:11111111-1111-4111-8111-111111111111',
       '${DATE}', '09:00', 'Água', '500 ml', 'app');
  `);
  const first = confirmTotal("app:22222222-2222-4222-8222-222222222222", "2500 ml", "11:00", 300);
  await new Promise((resolve) => setTimeout(resolve, 60));
  const second = confirmTotal("app:33333333-3333-4333-8333-333333333333", "2800 ml", "12:00");
  const [a, b] = await Promise.all([first, second]);
  expect(a.import_key).toBe(b.import_key);
  expect((await confirmTotal(
    "app:44444444-4444-4444-8444-444444444444", "2800 ml", "12:00",
  )).import_key).toBe(a.import_key);
  await psql(`
    insert into public.hidratacao
      (owner_id, import_key, data, horario, item, quantidade, source_file_id)
    values
      ('${OWNER_ID}', 'app:55555555-5555-4555-8555-555555555555',
       '${DATE}', '13:00', 'Água', '250 ml', 'app');
  `);
  const rows = JSON.parse((await psql(`
    select json_agg(json_build_object(
      'data', data, 'horario', horario, 'item', item,
      'quantidade', quantidade, 'import_key', import_key
    ) order by horario)::text from public.hidratacao where owner_id = '${OWNER_ID}';
  `)).trim());
  expect(rows).toHaveLength(3);
  expect(rows.filter((row) => row.item === "Total diário de água")).toHaveLength(1);
  expect(rows.filter((row) => row.item === "Água")).toHaveLength(2);
  await expect(psql(`
    insert into public.hidratacao
      (owner_id, import_key, data, horario, item, quantidade, source_file_id)
    values
      ('${OWNER_ID}', 'app:66666666-6666-4666-8666-666666666666',
       '${DATE}', '14:00', 'Total diário de água', '3000 ml', 'app');
  `)).rejects.toThrow("duplicate key");
  const oldSecret = process.env.SESSION_SECRET;
  process.env.SESSION_SECRET = "test-only-water-concurrency";
  try {
    const connectors = {
      proxy: async (_name, path) => ({
        ok: true,
        json: async () => path.startsWith("/rest/v1/hidratacao?")
          ? rows.filter((row) => row.data === DATE) : [],
      }),
    };
    expect((await dailySummary(connectors, DATE, OWNER_ID)).agua_ml).toBe(3050);
    expect((await weeklySummary(connectors, DATE, OWNER_ID)).dias.at(-1).agua_ml).toBe(3050);
  } finally {
    if (oldSecret === undefined) delete process.env.SESSION_SECRET;
    else process.env.SESSION_SECRET = oldSecret;
  }
  await psql(`
    create or replace function public.health_app_request_authorized() returns boolean
      language sql stable as 'select false';
  `);
  await expect(confirmTotal(
    "app:77777777-7777-4777-8777-777777777777", "3000 ml", "14:00",
  )).rejects.toThrow("Acesso não autorizado");
}, 30_000);