integrationTest("editing or deleting an owned total changes the daily and weekly readings but never doses", async () => {
  await psql(`
    insert into public.hidratacao
      (owner_id, import_key, data, horario, item, quantidade, source_file_id)
    values
      ('${OWNER_ID}', 'app:11111111-1111-4111-8111-111111111111',
       '${DATE}', '09:00', 'Água', '250 ml', 'app'),
      ('${OWNER_ID}', 'app:55555555-5555-4555-8555-555555555555',
       '${DATE}', '20:00', 'Água', '300 ml', 'app'),
      ('00000000-0000-4000-8000-000000000001',
       'app:88888888-8888-4888-8888-888888888888',
       '${DATE}', '18:00', 'Total diário de água', '4000 ml', 'app');
  `);
  const key = "app:22222222-2222-4222-8222-222222222222";
  await confirmTotal(key, "2500 ml", "18:00");
  expect(await correctTotal("00000000-0000-4000-8000-000000000001", key, "2500 ml", "delete"))
    .toEqual({ ok: false });
  expect(await correctTotal(OWNER_ID, key, "2400 ml", "update", 2000))
    .toEqual({ ok: false });
  expect(await correctTotal(
    OWNER_ID, "app:11111111-1111-4111-8111-111111111111", "250 ml", "delete",
  )).toEqual({ ok: false });
  expect(await correctTotal(OWNER_ID, key, "2500 ml", "update", 2000))
    .toEqual({ ok: true });
  expect(await correctTotal(OWNER_ID, key, "2500 ml", "delete"))
    .toEqual({ ok: false });

  const oldSecret = process.env.SESSION_SECRET;
  process.env.SESSION_SECRET = "test-only-water-corrections";
  try {
    async function connectors() {
      const records = JSON.parse((await psql(`
        select json_agg(json_build_object(
          'data', data, 'horario', horario, 'item', item,
          'quantidade', quantidade, 'import_key', import_key
        ) order by horario)::text from public.hidratacao where owner_id = '${OWNER_ID}';
      `)).trim());
      return {
        proxy: async (_name, path) => ({
          ok: true,
          json: async () => path.startsWith("/rest/v1/hidratacao?") ? records : [],
        }),
      };
    }
    let connection = await connectors();
    expect((await waterHistoryForDay(connection, DATE, OWNER_ID)).total_declarado.quantidade_ml).toBe(2000);
    expect((await waterHistoryForDay(connection, DATE, OWNER_ID)).doses).toHaveLength(2);
    expect((await dailySummary(connection, DATE, OWNER_ID)).agua_ml).toBe(2300);
    expect((await weeklySummary(connection, DATE, OWNER_ID)).dias.at(-1).agua_ml).toBe(2300);
    expect(await correctTotal(OWNER_ID, key, "2000 ml", "delete")).toEqual({ ok: true });
    connection = await connectors();
    expect((await waterHistoryForDay(connection, DATE, OWNER_ID)).total_declarado).toBeNull();
    expect((await waterHistoryForDay(connection, DATE, OWNER_ID)).doses).toHaveLength(2);
    expect((await dailySummary(connection, DATE, OWNER_ID)).agua_ml).toBe(550);
    expect((await weeklySummary(connection, DATE, OWNER_ID)).dias.at(-1).agua_ml).toBe(550);
  } finally {
    if (oldSecret === undefined) delete process.env.SESSION_SECRET;
    else process.env.SESSION_SECRET = oldSecret;
  }
  expect((await psql(`
    select count(*) from public.hidratacao
    where owner_id = '00000000-0000-4000-8000-000000000001'
      and item = 'Total diário de água';
  `)).trim()).toBe("1");
}, 30_000);

