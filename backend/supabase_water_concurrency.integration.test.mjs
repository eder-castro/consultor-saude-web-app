async function run(command, args, input) {
  const child = Bun.spawn([command, ...args], {
    stdin: input === undefined ? "ignore" : new Blob([input]),
    stdout: "pipe",
    stderr: "pipe",
  });
  const [code, stdout, stderr] = await Promise.all([
    child.exited, new Response(child.stdout).text(), new Response(child.stderr).text(),
  ]);
  if (code !== 0) throw new Error(`${command} failed: ${stderr || stdout}`);
  return stdout;
}

async function psql(sql) {
  return run(join(bin, "psql"), [
    "--no-psqlrc", "--set", "ON_ERROR_STOP=1", "--quiet", "--tuples-only", "--no-align",
    "--host", socket, "--username", "postgres", "--dbname", "postgres",
  ], sql);
}

async function confirmTotal(key, amount, time, holdMs = 0) {
  const output = await psql(`
    begin;
    select public.upsert_daily_water_total(
      '${OWNER_ID}', '${DATE}', '${time}', '${amount}', '${key}'
    )::text;
    ${holdMs ? `select pg_sleep(${holdMs / 1000});` : ""}
    commit;
  `);
  const result = output.split("\n").find((line) => line.trim().startsWith("{"));
  if (!result) throw new Error(`Missing database result: ${output}`);
  return JSON.parse(result);
}

async function correctTotal(ownerId, key, expected, action, nextAmount = null) {
  const output = await psql(`
    select public.correct_daily_water_total(
      '${ownerId}', '${DATE}', '${key}', '${expected}', '${action}',
      ${nextAmount === null ? "null" : nextAmount}
    )::text;
  `);
  return JSON.parse(output.trim());
}

